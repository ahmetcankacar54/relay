// Writes native/widget/WidgetStrings.swift from the catalogs' `widget.*` ids, so the
// widget's gallery names and fallbacks speak every language Relay does.
// Run: node --import tsx scripts/i18n/widget-strings.ts [--check]
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { CATALOGS } from "../../shared/i18n/catalogs/all";
import { LOCALES } from "../../shared/i18n/locales";

const ROOT = path.resolve(import.meta.dirname, "../..");
const out = path.join(ROOT, "native/widget/WidgetStrings.swift");
const swift = (s: string) => JSON.stringify(s).replace(/\\u([0-9a-fA-F]{4})/g, (_, h) => `\\u{${h}}`);
const ids = Object.keys(CATALOGS.en).filter((id) => id.startsWith("widget.")).sort();
const lines = [
  "// Generated by scripts/i18n/widget-strings.ts from shared/i18n/catalogs. Do not edit.",
  "let widgetStrings: [String: [String: String]] = [",
  ...LOCALES.map((locale) => {
    const catalog = CATALOGS[locale] as Record<string, string>;
    return `    ${swift(locale)}: [\n${ids.map((id) => `        ${swift(id)}: ${swift(catalog[id])},`).join("\n")}\n    ],`;
  }),
  "]",
  "",
];
const text = lines.join("\n");
if (process.argv.includes("--check")) {
  const current = (() => {
    try {
      return readFileSync(out, "utf8");
    } catch {
      return "";
    }
  })();
  if (current !== text) {
    console.error("WidgetStrings.swift is out of date: run node --import tsx scripts/i18n/widget-strings.ts");
    process.exit(1);
  }
} else writeFileSync(out, text);
