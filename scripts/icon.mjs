import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("..", import.meta.url));
const assets = path.join(root, "assets");
const icons = path.join(assets, "icons");
await mkdir(icons, { recursive: true });

// The Imagegen artwork stays unchanged. Apply the native rounded-square safe
// area when rendering packaging assets to keep a clean, reproducible silhouette.
const artwork = await readFile(path.join(assets, "icon-artwork.png"));
const appSvg =
  Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1280 1280">
  <defs><clipPath id="tile"><rect x="106" y="106" width="1048" height="1048" rx="238"/></clipPath></defs>
  <g clip-path="url(#tile)">
    <rect x="106" y="106" width="1048" height="1048" rx="238" fill="#faf3e8"/>
    <image href="data:image/png;base64,${artwork.toString("base64")}" x="0" y="0" width="1280" height="1280"/>
  </g>
</svg>`);
const traySvg = await readFile(path.join(assets, "trayTemplate.svg"), "utf8");
const sizes = [16, 32, 64, 128, 256, 512, 1024];
const appPngs = new Map();
for (const size of sizes) {
  const png = await sharp(appSvg).resize(size, size).png().toBuffer();
  appPngs.set(size, png);
  await writeFile(path.join(icons, `app-${size}.png`), png);
}
await writeFile(path.join(assets, "icon.png"), appPngs.get(1024));

// The same PNG-backed ICNS entries used by electron-builder's icon tool. Writing
// the container directly makes asset generation reproducible on every platform.
const icnsFrames = [
  ["icp4", 16],
  ["icp5", 32],
  ["icp6", 64],
  ["ic07", 128],
  ["ic08", 256],
  ["ic09", 512],
  ["ic10", 1024],
  ["ic11", 32],
  ["ic12", 64],
  ["ic13", 512],
  ["ic14", 1024],
].flatMap(([type, size]) => {
  const png = appPngs.get(size);
  const header = Buffer.alloc(8);
  header.write(type, 0, "ascii");
  header.writeUInt32BE(png.length + 8, 4);
  return [header, png];
});
const icnsBody = Buffer.concat(icnsFrames);
const icnsHeader = Buffer.alloc(8);
icnsHeader.write("icns", 0, "ascii");
icnsHeader.writeUInt32BE(icnsBody.length + 8, 4);
await writeFile(
  path.join(assets, "icon.icns"),
  Buffer.concat([icnsHeader, icnsBody]),
);

// Embed the small tray images in the main-process bundle so packaged apps never
// depend on source asset paths. Explicit scale factors retain crisp Retina edges.
const trayImages = {};
for (const [variant, color] of [
  ["template", "#000"],
  ["color", "#c54819"],
]) {
  trayImages[variant] = [];
  for (const scaleFactor of [1, 2, 3]) {
    const svg = traySvg.replaceAll("#000", color);
    const png = await sharp(Buffer.from(svg), { density: 72 * scaleFactor })
      .resize(20 * scaleFactor, 20 * scaleFactor)
      .png()
      .toBuffer();
    const suffix = scaleFactor === 1 ? "" : `@${scaleFactor}x`;
    const name = variant === "template" ? "trayTemplate" : "tray";
    await writeFile(path.join(assets, `${name}${suffix}.png`), png);
    trayImages[variant].push({ scaleFactor, png: png.toString("base64") });
  }
}
await writeFile(
  path.join(root, "electron", "tray-icons.ts"),
  "// Generated by scripts/icon.mjs from assets/trayTemplate.svg.\n" +
    "// Regenerate with npm run icons; edit the SVG source instead.\n" +
    `export const trayIcons = ${JSON.stringify(trayImages, null, 2)} as const;\n`,
);

