const byText = new Map<string, MessageId>(BACKEND_ERRORS.map(([text, id]) => [text, id]));

/** A backend error with variable parts: its pattern, its message and the message’s values. */
interface Pattern {
  match: RegExp;
  id: MessageId;
  params(m: RegExpExecArray, language: Locale): Params;
}
const patterns: Pattern[] = [
  // electron/core/vault-key.ts (VaultKeyError) and vault-migration.ts, around the Keychain item.
  { match: /^The Keychain item "([^"]+)" was not found\.$/, id: "errors.keychainItemNotFound", params: (m) => ({ item: m[1] }) },
  {
    match: /^The Keychain item "([^"]+)" could not be read\. Unlock the login keychain and try again\.$/,
    id: "errors.keychainItemUnlock",
    params: (m) => ({ item: m[1] }),
  },
  { match: /^The Keychain item "([^"]+)" does not hold a vault key\.$/, id: "errors.keychainItemNoVaultKey", params: (m) => ({ item: m[1] }) },
  {
    match:
      /^The Keychain item "([^"]+)" could not be read, so saved Claude app sign-ins cannot be opened\.(?: (.*?))?( To start over, run relay reset-vault \(npm i -g @ahmetcankacar\/relay\) and save each account again\.)?$/s,
    id: "errors.keychainVaultUnreadable",
    params: (m, language) => ({
      item: m[1],
      detail: m[2] ? ` ${localizeError(m[2], language)}` : "",
      reset: m[3] ? tFor(language)("errors.keychainResetHint") : "",
    }),
  },
  {
    match: /^The Keychain item "([^"]+)" could not be read\. (.+)$/s,
    id: "errors.keychainItemUnreadableDetail",
    params: (m, language) => ({ item: m[1], detail: localizeError(m[2], language) }),
  },
  {
    match: /^Relay’s saved sign-ins could not be read: (.*)$/s,
    id: "errors.savedSignInsUnreadable",
    params: (m, language) => ({ detail: localizeError(m[1], language) }),
  },
  {
    match: /^Relay’s saved sign-ins were written by a newer version \(format (\d+)\)\. Update Relay\.$/,
    id: "errors.savedSignInsNewerFormat",
    params: (m) => ({ format: m[1] }),
  },
  {
    match:
      /^(\d+) saved sign-in files? could not be opened and (?:was|were) set aside in desktop-vault\/unreadable\. Save the affected accounts’ Claude app sign-ins again\.$/,
    id: "errors.signInFilesSetAside",
    params: (m) => ({ count: Number(m[1]) }),
  },
];

/** `message` in `language`: a known backend error is translated, anything else is left as it is. */
export function localizeError(message: string, language: Locale): string {
  const id = byText.get(message);
  if (id) return tFor(language)(id);
  for (const pattern of patterns) {
    const match = pattern.match.exec(message);
    if (match) return tFor(language)(pattern.id, pattern.params(match, language));
  }
  return message;
}
